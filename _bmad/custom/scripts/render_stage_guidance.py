"""Generate the implementation pilot directly from the authoritative contract manual.

No workflow routing or validation decisions happen here. --check detects stale/missing
instructions without changing files; in that case the agent must read the full manual.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

if __package__:
    from .validate_story_contract import ContractDocument
else:
    from validate_story_contract import ContractDocument

SECTION = "Developer rules (implementation subagent)"
MANUAL = "story-contract.md"
OUTPUT = Path("instructions/implementation.md")
REQUIRED = (
    "### Mandatory preflight",
    "validate --phase approved <spec_file>",
    "HALT on failure",
    "### Implementation obligations",
    "### Stop conditions and exception index",
    "An omission is never permission",
    "read the **full**",
)


def render_implementation(manual: Path) -> str:
    text = manual.read_text(encoding="utf-8")
    document = ContractDocument.from_text(manual, text)
    sections = [s for s in document.sections if s.level == 2 and s.title == SECTION]
    if len(sections) != 1:
        raise ValueError(f"{MANUAL} must have exactly one '## {SECTION}' section")
    section = sections[0]
    excerpt = "\n".join(document.lines[section.start : section.end]).rstrip()
    for required in REQUIRED:
        if required not in excerpt:
            raise ValueError(
                f"canonical implementation guidance is missing: {required}"
            )
    # Self-links in the manual must still point to the manual from this generated file.
    excerpt = excerpt.replace("](#", "](../story-contract.md#")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return (
        "# Implementation instructions\n\n"
        "<!-- Generated by render_stage_guidance.py; do not edit this file. -->\n"
        f"<!-- Source SHA-256: {digest} -->\n\n"
        "Source: [full contract manual](../story-contract.md#developer-rules-implementation-subagent)\n"
        "(`_bmad/custom/story-contract.md`). This is an exact section extraction, not a\n"
        "summary. Planning, approval and independent review still use the full manual.\n\n"
        + excerpt
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if instructions are stale or missing"
    )
    parser.add_argument(
        "--custom-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="customisations directory (default: this script's parent custom tree)",
    )
    args = parser.parse_args(argv)
    custom = args.custom_dir.resolve()
    output = custom / OUTPUT
    try:
        if not output.resolve().is_relative_to(custom):
            raise ValueError(
                "generated instructions path leaves the customisations tree"
            )
        expected = render_implementation(custom / MANUAL)
        if args.check:
            if not output.is_file() or output.read_text(encoding="utf-8") != expected:
                print(
                    f"STALE or missing {output}. Read the full {custom / MANUAL} before "
                    "continuing; review source changes and regenerate the instructions.",
                    file=sys.stderr,
                )
                return 1
            print("Implementation instructions match the canonical manual.")
        else:
            output.parent.mkdir(parents=True, exist_ok=True)
            output.write_text(expected, encoding="utf-8")
            print(f"Generated {output}")
    except (OSError, UnicodeError, ValueError) as error:
        print(
            f"ERROR: {error}. Read the full {custom / MANUAL}; do not improvise.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
